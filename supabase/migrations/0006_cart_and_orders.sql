-- payments ----------------------------------------------------------
-- 1:N with orders (payment attempts), not 1:1 -- a rejected manual
-- transfer can be resubmitted with a corrected reference. orders.
-- payment_status remains the single authoritative current state. See
-- DECISIONS.md D18 / ARCHITECTURE.md, Payment Abstraction.

create table public.payments (
  id uuid primary key default gen_random_uuid(),
  order_id uuid not null references public.orders (id) on delete cascade,
  payment_method_id uuid not null references public.payment_methods (id),
  amount numeric(10, 2) not null check (amount >= 0),
  status text not null default 'PENDING' check (
    status in ('PENDING', 'AWAITING_VERIFICATION', 'VERIFIED', 'REJECTED', 'REFUNDED')
  ),
  transaction_reference text,
  proof_image_url text,
  verified_by uuid references public.profiles (id),
  verified_at timestamptz,
  notes text,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

create index payments_order_id_idx on public.payments (order_id);

create trigger payments_touch_updated_at
  before update on public.payments
  for each row execute function public.touch_updated_at();

alter table public.payments enable row level security;

create policy payments_owner_select on public.payments
  for select using (
    exists (select 1 from public.orders o where o.id = payments.order_id and o.profile_id = auth.uid())
  );

create policy payments_admin_select on public.payments
  for select using (public.is_admin());

